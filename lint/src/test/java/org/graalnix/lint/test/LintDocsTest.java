package org.graalnix.lint.test;

import static org.assertj.core.api.Assertions.assertThat;
import static org.junit.jupiter.api.Assumptions.assumeTrue;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.EnumSet;
import java.util.Locale;
import java.util.Set;
import java.util.stream.Collectors;
import org.graalnix.lint.Linter;
import org.graalnix.lint.Rule;
import org.junit.jupiter.api.Test;

/**
 * Generates docs/_lint-rules.adoc from the cases: each rule shows its case's input, diagnostics and fixed output in
 * tabs. When the file is out of date, the test rewrites it and fails, so that the new version gets committed.
 */
class LintDocsTest {
    /** Tests run from the project root; the Nix build of the tests includes the generated file. */
    private static final Path DOCS = Path.of("docs");

    private static final Path GENERATED = DOCS.resolve("_lint-rules.adoc");

    private record Group(String title, String intro, Set<Rule> rules) {}

    private static final Group[] GROUPS = {
        new Group(
                "Dead code",
                "Bindings that nothing uses, as https://github.com/astro/deadnix[deadnix] finds them."
                        + " Names starting with `_` are never reported.",
                EnumSet.range(Rule.UNUSED_LET_BINDING, Rule.UNUSED_AT_PATTERN)),
        new Group(
                "Simpler forms",
                "Code with a simpler or more idiomatic form, as https://github.com/oppiliappan/statix[statix] finds"
                        + " it.",
                EnumSet.range(Rule.BOOL_COMPARISON, Rule.REPEATED_KEYS)),
        new Group(
                "Semantics",
                "Checks that need name resolution, as https://github.com/nix-community/nixd[nixd] makes them.",
                EnumSet.range(Rule.UNDEFINED_VARIABLE, Rule.EXTRA_WITH)),
        new Group(
                "Packaging",
                "Conventions of nixpkgs for derivations.",
                EnumSet.range(Rule.MISSING_PHASE_HOOKS, Rule.MISSING_STRUCTURED_ATTRS)),
    };

    @Test
    void docsAreUpToDate() throws IOException {
        assumeTrue(Files.isDirectory(DOCS), "no docs/ in " + Path.of("").toAbsolutePath());
        String doc = generate();
        String committed = Files.exists(GENERATED) ? Files.readString(GENERATED, StandardCharsets.UTF_8) : "";
        if (!doc.equals(committed)) Files.writeString(GENERATED, doc, StandardCharsets.UTF_8);
        assertThat(committed)
                .as(GENERATED + " was out of date and has been rewritten")
                .isEqualTo(doc);
    }

    @Test
    void everyRuleIsInAGroup() {
        Set<Rule> grouped = EnumSet.noneOf(Rule.class);
        for (Group g : GROUPS) grouped.addAll(g.rules());
        assertThat(grouped).isEqualTo(EnumSet.complementOf(EnumSet.of(Rule.SYNTAX_ERROR)));
    }

    private static String generate() throws IOException {
        StringBuilder sb = new StringBuilder();
        sb.append("// Generated by LintDocsTest from lint/src/test/java/cases/: do not edit.\n");
        sb.append("[[lint-rules]]\n= Lint rules\n\n");
        sb.append("Each rule shows a case from the linter's tests: the original code, what `Linter.fix` makes of it,"
                + " and what `Linter.lint` reports, with `[fix]` after the findings that come with a fix.\n\n");
        sb.append("[cols=\"3,1,8\"]\n|===\n|Rule |Severity |Description\n\n");
        for (Rule r : Rule.values()) {
            sb.append("|<<").append(anchor(r)).append(",`").append(r.id()).append("`>>\n");
            sb.append("|").append(severity(r)).append('\n');
            sb.append("|").append(r.description()).append("\n\n");
        }
        sb.append("|===\n\n");

        sb.append("== Syntax errors\n\n");
        String invalid = "{\n  a = 1;\n  a = 2;\n}\n";
        rule(sb, Rule.SYNTAX_ERROR, invalid, diagnostics(invalid, "syntax-error.nix"), invalid);
        for (Group g : GROUPS) {
            sb.append("== ").append(g.title()).append("\n\n").append(g.intro()).append("\n\n");
            for (Rule r : g.rules()) {
                Path cases = LintTest.CASES;
                rule(
                        sb,
                        r,
                        LintTest.read(cases.resolve(r.id() + ".nix")),
                        LintTest.read(cases.resolve(r.id() + ".expected")),
                        LintTest.read(cases.resolve(r.id() + ".fixed.nix")));
            }
        }
        return sb.toString().replaceAll("\n+$", "\n");
    }

    private static String diagnostics(String src, String name) {
        return Linter.lint(src).stream().map(d -> d.render(src, name) + "\n").collect(Collectors.joining());
    }

    private static void rule(StringBuilder sb, Rule r, String input, String diagnostics, String fixed) {
        sb.append("[[").append(anchor(r)).append("]]\n");
        sb.append("=== `").append(r.id()).append("`\n\n");
        sb.append("Severity: ")
                .append(severity(r))
                .append(". ")
                .append(r.description())
                .append("\n\n");
        tab(sb, "primary", "nix", "Original", input);
        if (!fixed.equals(input)) tab(sb, "secondary", "nix", "Fixed", fixed);
        tab(sb, "secondary", "text", "Diagnostics", diagnostics);
    }

    /** The markup of asciidoctorj-tabbed-code-extension, which docs/docinfo.html turns into tabs. */
    private static void tab(StringBuilder sb, String role, String language, String title, String content) {
        sb.append("[source,").append(language).append(",role=\"").append(role).append("\"]\n");
        sb.append('.').append(title).append('\n');
        sb.append("----\n")
                .append(content.endsWith("\n") ? content : content + "\n")
                .append("----\n\n");
    }

    private static String anchor(Rule r) {
        return "lint-" + r.id();
    }

    private static String severity(Rule r) {
        return r.severity().name().toLowerCase(Locale.ROOT);
    }
}
